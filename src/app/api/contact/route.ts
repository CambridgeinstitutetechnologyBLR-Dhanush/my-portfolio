import { NextResponse } from 'next/server';

export async function POST(request: Request) {
  try {
    const body = await request.json();
    const { name, email, subject, message } = body;

    // Validate presence
    if (!name || !email || !subject || !message) {
      return NextResponse.json(
        { error: 'All fields (name, email, subject, message) are required.' },
        { status: 400 }
      );
    }

    // Validate email format
    const emailRegex = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
    if (!emailRegex.test(email)) {
      return NextResponse.json(
        { error: 'Please enter a valid email address.' },
        { status: 400 }
      );
    }

    if (message.trim().length < 10) {
      return NextResponse.json(
        { error: 'Message must be at least 10 characters long.' },
        { status: 400 }
      );
    }

    // Log the contact inquiry on server console
    console.log('[Portfolio Contact Form Submission]', {
      timestamp: new Date().toISOString(),
      name,
      email,
      subject,
      messageLength: message.length
    });

    return NextResponse.json(
      {
        success: true,
        message: 'Thank you! Your message has been received. I will get back to you shortly.',
        data: { name, email, subject }
      },
      { status: 200 }
    );
  } catch (error) {
    console.error('Contact API error:', error);
    return NextResponse.json(
      { error: 'Internal server error while processing message.' },
      { status: 500 }
    );
  }
}
